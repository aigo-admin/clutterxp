"""Preview view for execution plans, filtering, move exclusion, and apply.

Displays the plan generated by the Organizer, allows excluding individual items,
filtering by plan status, inspecting ambiguous rules, and applying moves with confirmation.
"""

from __future__ import annotations

from pathlib import Path

from PySide6.QtCore import Signal
from PySide6.QtWidgets import (
    QComboBox,
    QFileDialog,
    QHBoxLayout,
    QHeaderView,
    QLabel,
    QLineEdit,
    QMessageBox,
    QProgressBar,
    QPushButton,
    QTableView,
    QVBoxLayout,
    QWidget,
)

from clutterxp.gui.api import GuiApi
from clutterxp.gui.models_qt import PlanTableModel
from clutterxp.gui.workers import run_in_worker
from clutterxp.models import BatchResult, Plan, PlanStatus


class PreviewView(QWidget):
    """Plan preview table, filter, item exclusion, and apply controls."""

    navigate_requested = Signal(str)  # e.g. "rules"
    open_rule_requested = Signal(str)  # rule_name to edit

    def __init__(self, api: GuiApi, parent: QWidget | None = None) -> None:
        super().__init__(parent)
        self.api = api
        self._current_plan: Plan = Plan(folders=(), actions=())
        self._model = PlanTableModel()
        self._init_ui()

    def _init_ui(self) -> None:
        main_layout = QVBoxLayout(self)
        main_layout.setContentsMargins(16, 16, 16, 16)
        main_layout.setSpacing(12)

        # Header
        header_layout = QVBoxLayout()
        header_layout.setSpacing(2)
        title_label = QLabel("Preview & Organize")
        title_font = title_label.font()
        title_font.setPointSize(18)
        title_font.setBold(True)
        title_label.setFont(title_font)
        title_label.setStyleSheet("color: #f8fafc;")
        header_layout.addWidget(title_label)

        subtitle_label = QLabel(
            "Preview exactly what will move before touching any files. Zero risk, 100% undoable."
        )
        subtitle_label.setStyleSheet("color: #94a3b8; font-size: 12px;")
        header_layout.addWidget(subtitle_label)
        main_layout.addLayout(header_layout)

        # Top Control Row: Scan Target + Scan Button
        target_row = QHBoxLayout()
        target_row.setSpacing(8)
        lbl_target = QLabel("Target Folder:")
        lbl_target.setStyleSheet("color: #cbd5e1; font-weight: 500;")
        target_row.addWidget(lbl_target)

        self.path_edit = QLineEdit()
        self.path_edit.setPlaceholderText(
            "Default: all configured watch folders (e.g. ~/Downloads)"
        )
        target_row.addWidget(self.path_edit, stretch=1)

        self.browse_btn = QPushButton("Browse...")
        self.browse_btn.clicked.connect(self._on_browse)
        target_row.addWidget(self.browse_btn)

        self.scan_btn = QPushButton("🔍 Scan Plan")
        self.scan_btn.setProperty("primary", True)
        self.scan_btn.clicked.connect(self.scan)
        target_row.addWidget(self.scan_btn)

        main_layout.addLayout(target_row)

        # Filter & Selection Controls Row
        filter_row = QHBoxLayout()
        filter_row.setSpacing(8)
        lbl_filter = QLabel("Filter:")
        lbl_filter.setStyleSheet("color: #94a3b8;")
        filter_row.addWidget(lbl_filter)

        self.filter_combo = QComboBox()
        self.filter_combo.addItem("All Items", "all")
        self.filter_combo.addItem("Will Move Only", "will_move")
        self.filter_combo.addItem("Ambiguous", "ambiguous")
        self.filter_combo.addItem("Blocked", "blocked")
        self.filter_combo.addItem("Unmatched / Ignored", "unmatched")
        self.filter_combo.currentIndexChanged.connect(self._on_filter_changed)
        filter_row.addWidget(self.filter_combo)

        self.select_all_btn = QPushButton("Select All")
        self.select_all_btn.clicked.connect(lambda: self._model.toggle_all(True))
        filter_row.addWidget(self.select_all_btn)

        self.deselect_all_btn = QPushButton("Deselect All")
        self.deselect_all_btn.clicked.connect(lambda: self._model.toggle_all(False))
        filter_row.addWidget(self.deselect_all_btn)

        self.inspect_btn = QPushButton("Inspect Ambiguous")
        self.inspect_btn.setEnabled(False)
        self.inspect_btn.clicked.connect(self._on_inspect_ambiguous)
        filter_row.addWidget(self.inspect_btn)

        filter_row.addStretch()
        main_layout.addLayout(filter_row)

        # Plan Table
        self.table = QTableView()
        self.table.setModel(self._model)
        self.table.setAlternatingRowColors(True)
        self.table.setShowGrid(False)
        self.table.setSelectionBehavior(QTableView.SelectionBehavior.SelectRows)
        self.table.setSelectionMode(QTableView.SelectionMode.SingleSelection)
        self.table.verticalHeader().setDefaultSectionSize(32)
        self.table.horizontalHeader().setSectionResizeMode(QHeaderView.ResizeMode.ResizeToContents)
        self.table.horizontalHeader().setStretchLastSection(True)
        self.table.selectionModel().selectionChanged.connect(self._on_selection_changed)
        self._model.plan_changed.connect(self._update_summary_label)
        main_layout.addWidget(self.table, stretch=1)

        # Progress bar
        self.progress_bar = QProgressBar()
        self.progress_bar.setVisible(False)
        main_layout.addWidget(self.progress_bar)

        # Bottom Row: Summary & Apply Button
        bottom_row = QHBoxLayout()
        self.summary_label = QLabel("No active plan. Click 'Scan Plan' to generate preview.")
        self.summary_label.setStyleSheet("color: #94a3b8; font-size: 13px;")
        bottom_row.addWidget(self.summary_label)

        bottom_row.addStretch()

        self.apply_btn = QPushButton("Apply Selected Moves")
        self.apply_btn.setProperty("success", True)
        self.apply_btn.setStyleSheet("font-weight: bold; padding: 7px 20px; font-size: 13px;")
        self.apply_btn.clicked.connect(self._on_apply)
        bottom_row.addWidget(self.apply_btn)

        main_layout.addLayout(bottom_row)

    @property
    def model(self) -> PlanTableModel:
        return self._model

    def set_plan(self, plan: Plan) -> None:
        """Set plan directly (useful for tests and sync updates)."""
        self._current_plan = plan
        self._model.set_plan(plan)
        self._update_summary_label()

    def scan(self) -> None:
        """Scan folders and generate execution plan in background worker."""
        target_str = self.path_edit.text().strip()
        paths_to_scan = [Path(target_str)] if target_str else None

        self.scan_btn.setEnabled(False)
        self.progress_bar.setVisible(True)
        self.progress_bar.setRange(0, 0)  # indeterminate

        def _do_scan() -> Plan:
            return self.api.plan(paths_to_scan=paths_to_scan)

        def _on_done(plan: Plan) -> None:
            self.scan_btn.setEnabled(True)
            self.progress_bar.setVisible(False)
            self.set_plan(plan)

        def _on_err(exc: Exception) -> None:
            self.scan_btn.setEnabled(True)
            self.progress_bar.setVisible(False)
            QMessageBox.critical(self, "Plan Scan Failed", str(exc))

        run_in_worker(_do_scan, on_result=_on_done, on_error=_on_err)

    def _on_browse(self) -> None:
        chosen = QFileDialog.getExistingDirectory(self, "Select Folder to Scan")
        if chosen:
            self.path_edit.setText(chosen)

    def _on_filter_changed(self) -> None:
        filter_name = self.filter_combo.currentData()
        self._model.set_filter(filter_name)
        self._update_summary_label()

    def _on_selection_changed(self) -> None:
        selected_indexes = self.table.selectionModel().selectedRows()
        if not selected_indexes:
            self.inspect_btn.setEnabled(False)
            return

        action = self._model.get_action(selected_indexes[0].row())
        if action and (action.status == PlanStatus.AMBIGUOUS or action.decision.candidates):
            self.inspect_btn.setEnabled(True)
        else:
            self.inspect_btn.setEnabled(False)

    def _on_inspect_ambiguous(self) -> None:
        selected_indexes = self.table.selectionModel().selectedRows()
        if not selected_indexes:
            return
        action = self._model.get_action(selected_indexes[0].row())
        if not action or not action.decision.candidates:
            return

        cand_names = [c.rule_name for c in action.decision.candidates]
        msg = (
            f"File: {action.file.name}\n\n"
            f"Matched {len(cand_names)} candidate rules at the same priority:\n"
            + "\n".join(f"- {name}" for name in cand_names)
            + "\n\nWould you like to open the Rules view to adjust priorities?"
        )
        reply = QMessageBox.question(
            self,
            "Ambiguous Rule Match",
            msg,
            QMessageBox.StandardButton.Yes | QMessageBox.StandardButton.No,
        )
        if reply == QMessageBox.StandardButton.Yes:
            self.open_rule_requested.emit(cand_names[0])
            self.navigate_requested.emit("rules")

    def _update_summary_label(self) -> None:
        plan = self._current_plan
        will_move = plan.count(PlanStatus.WILL_MOVE) + plan.count(PlanStatus.WILL_MOVE_RENAMED)
        ambig = plan.count(PlanStatus.AMBIGUOUS)
        blocked = plan.count(PlanStatus.BLOCKED)
        unmatched = plan.count(PlanStatus.NO_MATCH) + plan.count(PlanStatus.IGNORED)
        included = self._model.included_count

        self.summary_label.setText(
            f"Total: {len(plan.actions)} | "
            f"Will Move: {will_move} (Selected: {included}) | "
            f"Ambiguous: {ambig} | Blocked: {blocked} | Unmatched: {unmatched}"
        )

    def _on_apply(self) -> None:
        included_plan = self._model.get_included_plan()
        moves_count = len(included_plan.actions)
        if moves_count == 0:
            QMessageBox.information(
                self,
                "Nothing to Apply",
                "No files selected to move.",
            )
            return

        reply = QMessageBox.question(
            self,
            "Confirm Organization",
            f"Move {moves_count} selected file(s) to their destinations?",
            QMessageBox.StandardButton.Yes | QMessageBox.StandardButton.No,
        )
        if reply != QMessageBox.StandardButton.Yes:
            return

        self.apply_btn.setEnabled(False)
        self.progress_bar.setVisible(True)
        self.progress_bar.setRange(0, moves_count)
        self.progress_bar.setValue(0)

        def _do_apply() -> BatchResult:
            return self.api.apply(included_plan)

        def _on_done(res: BatchResult) -> None:
            self.apply_btn.setEnabled(True)
            self.progress_bar.setVisible(False)
            QMessageBox.information(
                self,
                "Organization Complete",
                f"Moved: {res.moved}\nSkipped: {res.skipped}\n"
                f"Blocked: {res.blocked}\nFailed: {res.failed}",
            )
            # Re-scan to reflect moves
            self.scan()

        def _on_err(exc: Exception) -> None:
            self.apply_btn.setEnabled(True)
            self.progress_bar.setVisible(False)
            QMessageBox.critical(self, "Apply Failed", str(exc))

        run_in_worker(_do_apply, on_result=_on_done, on_error=_on_err)


__all__ = ["PreviewView"]
